"use client";
/* eslint-disable @next/next/no-img-element */
import { DownloadOutlined, LinkOutlined, PrinterOutlined } from "@ant-design/icons";
import { Alert, App, Button, Descriptions, Image, Modal, Tag, Typography } from "antd";
import { akamaSections } from "@/lib/akamaFields";
import type { AdminAkama } from "@/lib/types";
import { copyText, formatDate, isDevUrl, printQr, QR_NOTE, qrDownloadUrl, qrImageUrl } from "./akamaUtils";

/**
 * "Akama Details" pop-up (opened by View / QR in the table, and automatically
 * right after a new record is created).
 *
 * Shows the image, the QR code of the permanent public URL with
 * Download / Print / Copy Public Link buttons, warnings (private record,
 * development URL), the certificate details (same Arabic labels and order as
 * the public card) and the record details.
 */
type Props = {
  record: AdminAkama | null;
  onClose: () => void;
  onEdit: (record: AdminAkama) => void;
};

const AkamaViewModal = ({ record, onClose, onEdit }: Props) => {
  const { message } = App.useApp();

  // The link is copied even for private records – it starts working once made public
  const copyLink = async (r: AdminAkama) => {
    if (await copyText(r.publicUrl)) {
      message.success(r.isPublic ? "Public link copied" : "Link copied. It will work once the record is public.");
    } else {
      message.error("Could not copy the link.");
    }
  };

  // Opens a print window (see printQr in akamaUtils.ts); fails only if pop-ups are blocked
  const print = (r: AdminAkama) => {
    if (!printQr(r)) message.error("Please allow pop-ups for this site to print the QR code.");
  };

  return (
    <Modal
      open={!!record}
      title="Akama Details"
      onCancel={onClose}
      width={720}
      footer={
        record && [
          <Button key="close" onClick={onClose}>
            Close
          </Button>,
          <Button key="edit" type="primary" onClick={() => onEdit(record)}>
            Edit
          </Button>,
        ]
      }
    >
      {record && (
        <div className="mt-4 space-y-5">
          <div className="grid gap-4 sm:grid-cols-[1fr_220px]">
            {/* Akama image (click to enlarge) */}
            <div className="flex items-center justify-center rounded-xl bg-brand-50/60 p-3">
              <Image
                src={record.imageUrl}
                alt={`Akama of ${record.name}`}
                style={{ maxHeight: 260, objectFit: "contain" }}
              />
            </div>

            {/* QR code for the permanent public link */}
            <div className="flex flex-col items-center rounded-xl border border-line p-3 text-center">
              {/* PNG generated by the server: GET /api/admin/akama/{id}/qr */}
              <img
                src={qrImageUrl(record.id)}
                alt={`QR code for ${record.name}`}
                width={160}
                height={160}
                className="size-40"
              />
              <p className="mt-1 text-xs text-ink-soft">Scan to open the public page</p>
              <div className="mt-3 flex w-full flex-col gap-2">
                {/* ?download=1 makes the server send it as a file named after the person */}
                <Button icon={<DownloadOutlined />} href={qrDownloadUrl(record.id)} download block>
                  Download QR Code
                </Button>
                <Button icon={<PrinterOutlined />} onClick={() => print(record)} block>
                  Print QR Code
                </Button>
                <Button icon={<LinkOutlined />} onClick={() => copyLink(record)} block>
                  Copy Public Link
                </Button>
              </div>
            </div>
          </div>

          {/* Explains why the QR code currently shows "not available" */}
          {!record.isPublic && (
            <Alert
              type="info"
              showIcon
              title="This record is private"
              description="The QR code and link show a “not available” page until you make the record public. They will start working without any changes."
            />
          )}
          {/* PUBLIC_APP_URL not set to the live site yet – don't print these codes */}
          {isDevUrl(record.publicUrl) && (
            <Alert
              type="warning"
              showIcon
              title="Links point to a development address"
              description="Set PUBLIC_APP_URL on the server to the live website before printing or sharing QR codes."
            />
          )}

          {/* Certificate details, one table per card section */}
          {akamaSections.map(section => (
            <Descriptions
              key={section.title}
              column={1}
              bordered
              size="small"
              title={
                <span>
                  <span dir="rtl" className="text-brand-600">{section.title}</span>{" "}
                  <span className="text-xs font-normal text-ink-soft">({section.hint})</span>
                </span>
              }
              styles={{ label: { width: 230 } }}
            >
              {section.fields.map(field => (
                <Descriptions.Item
                  key={field.key}
                  label={
                    <span>
                      <span dir="rtl">{field.label}</span> <span className="text-xs text-ink-soft">({field.hint})</span>
                    </span>
                  }
                >
                  {record[field.key] ? <span dir="auto">{record[field.key]}</span> : <span className="text-ink-soft">—</span>}
                </Descriptions.Item>
              ))}
            </Descriptions>
          ))}

          <Descriptions column={1} bordered size="small" title="Record" styles={{ label: { width: 230 } }}>
            <Descriptions.Item label="Akama ID">
              <Typography.Text copyable code>
                {record.id}
              </Typography.Text>
            </Descriptions.Item>
            <Descriptions.Item label="Visibility">
              {record.isPublic ? <Tag color="green">Public</Tag> : <Tag>Private</Tag>}
            </Descriptions.Item>
            <Descriptions.Item label="Public link">
              <a href={record.publicUrl} target="_blank" rel="noreferrer" className="break-all">
                {record.publicUrl}
              </a>
            </Descriptions.Item>
            <Descriptions.Item label="Created">{formatDate(record.createdAt)}</Descriptions.Item>
            <Descriptions.Item label="Last updated">{formatDate(record.updatedAt)}</Descriptions.Item>
          </Descriptions>

          <p className="text-xs text-ink-soft">{QR_NOTE}</p>
        </div>
      )}
    </Modal>
  );
};

export default AkamaViewModal;
