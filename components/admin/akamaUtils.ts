/**
 * Small helpers shared by the admin components (dashboard, form, details pop-up).
 */
import type { AdminAkama } from "@/lib/types";

// Date format for the table and details, e.g. "13 Oct 2026, 23:08"
const dateFormat = new Intl.DateTimeFormat("en-GB", {
  day: "2-digit",
  month: "short",
  year: "numeric",
  hour: "2-digit",
  minute: "2-digit",
});

/** ISO date string -> readable local date and time. */
export const formatDate = (iso: string) => dateFormat.format(new Date(iso));

// Shown before making a record public (confirm pop-up and form alert)
export const PUBLIC_WARNING =
  "Anyone with the link or QR code can see this person's Akama image, and the name, Akama ID and image will appear on the public Akama page. " +
  "People can save or copy the image. A public page is only for convenient sharing — it does not prove the Akama is genuine.";

// Disclaimer shown with every QR code (details pop-up and print page)
export const QR_NOTE =
  "The QR code only opens this record's page. It does not verify the Akama or provide any official verification.";

// QR PNGs are generated by the server from the record's permanent public URL
export const qrImageUrl = (id: string) => `/api/admin/akama/${id}/qr`;
export const qrDownloadUrl = (id: string) => `/api/admin/akama/${id}/qr?download=1`;

/** True when links would point at a development address instead of the live site. */
export const isDevUrl = (url: string) => /\/\/(localhost|127\.0\.0\.1)/.test(url);

/** Copies text to the clipboard. Returns false if the browser refused. */
export const copyText = async (text: string) => {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
};

/** Opens a print-ready page with the QR code, name and Akama ID. Returns false if pop-ups are blocked. */
export const printQr = (record: AdminAkama) => {
  const win = window.open("", "_blank", "width=640,height=820");
  if (!win) return false;
  const doc = win.document;
  doc.title = `QR Code – ${record.name}`;

  const style = doc.createElement("style");
  style.textContent = `
    body { font-family: system-ui, sans-serif; color: #1d2420; text-align: center; margin: 40px; }
    img { width: 320px; height: 320px; image-rendering: pixelated; }
    h1 { font-size: 24px; margin: 24px 0 6px; }
    .id { font-family: ui-monospace, monospace; font-size: 15px; }
    .url { font-size: 12px; color: #4a544e; word-break: break-all; margin-top: 12px; }
    .note { font-size: 11px; color: #6b746e; margin-top: 28px; }
    @page { margin: 16mm; }`;
  doc.head.appendChild(style);

  // Adds one line of text to the print page
  const add = (tag: string, text: string, className?: string) => {
    const el = doc.createElement(tag);
    el.textContent = text; // textContent: names are never interpreted as HTML
    if (className) el.className = className;
    doc.body.appendChild(el);
    return el;
  };

  const img = doc.createElement("img");
  img.alt = `QR code for ${record.name}`;
  doc.body.appendChild(img);
  add("h1", record.name);
  add("div", `Akama ID: ${record.id}`, "id");
  add("div", record.publicUrl, "url");
  add("div", QR_NOTE, "note");

  // Print only after the QR image has loaded, otherwise the page prints blank
  img.onload = () => {
    win.focus();
    win.print();
  };
  // Absolute URL: the new window is about:blank, so relative paths would not resolve
  img.src = `${window.location.origin}${qrImageUrl(record.id)}`;
  return true;
};
